/** Destino do redirecionamento, ou null se o endereço não é de uma notícia antiga. */
export function destinoDoEnderecoAntigo(pathname: string): string | null {
  let caminho: string;
  try {
    caminho = decodeURIComponent(pathname);
  } catch {
    return null;
  }
  caminho = caminho.replace(/\/+$/, "").toLowerCase();
  return enderecos.has(caminho) ? "/blog#arquivo" : null;
}
